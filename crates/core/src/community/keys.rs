//! The string-table keys the community screens use. Core emits keys and sanitized content,
//! never fixed text, so a theme or translation can change every word (`docs/ui.md`). The
//! server's string table must hold exactly these keys plus the menu tree's ([`TEXT_KEYS`]).

macro_rules! keys {
    ($($name:ident = $key:literal),+ $(,)?) => {
        $(
            #[doc = concat!("String-table key `", $key, "`.")]
            pub const $name: &str = $key;
        )+

        /// Every key above.
        pub const TEXT_KEYS: &[&str] = &[$($name),+];
    };
}

